https://graphty.app/docs/visual-review/`;

/**
 * The repository and its config, loaded only by the commands that need them.
 * @returns {Promise<{ root: string, config: object }>} the checkout's root and its settings
 */
async function settings() {
    const { loadConfig, repoRoot } = await import("./lib/config.mjs");
    const root = repoRoot();
    return { root, config: loadConfig(root) };
}

async function capture(args) {
    const { values } = parseArgs({
        args,
        options: {
            project: { type: "string" },
            out: { type: "string" },
            storybook: { type: "string" },
            baselines: { type: "string" },
            workers: { type: "string" },
            reference: { type: "string" },
            stories: { type: "string" },
        },
    });
    const { root, config } = await settings();
    const project = Object.hasOwn(config.projects, values.project ?? "") ? config.projects[values.project] : undefined;
    const workers = Number(values.workers ?? project?.workers);
    if (!project || !values.out || !(Number.isInteger(workers) && workers > 0)) {
        console.error(`${HELP.capture}\n\nprojects: ${Object.keys(config.projects).join(", ")}`);
        return 2;
    }
    // Playwright is capture's only dependency, so it loads only for this command.
    const { capture: run } = await import("../capture/capture.mjs");
    await run({
        project: values.project,
        storybook: resolve(values.storybook ?? join(root, project.storybook)),
        baselines: resolve(values.baselines ?? join(root, config.baselines, values.project)),
        out: resolve(values.out),
        workers,
        waitFor: project.waitFor,
        reference: values.reference ? resolve(values.reference) : null,
        stories: values.stories ? values.stories.split(",").filter(Boolean) : null,
    });
    return 0;
}

async function reference(args) {
    const { values } = parseArgs({ args, options: { project: { type: "string" }, out: { type: "string" } } });
    if (!values.project || !values.out) {
        console.error(HELP.reference);
        return 2;
    }
    const { root, config } = await settings();
    const { ghRunner, newestMasterCapture } = await import("./lib/github.mjs");
    console.log((await newestMasterCapture(ghRunner(root), values.project, resolve(values.out), config)) ?? "");
    return 0;
}

const LOOPBACK = new Set(["localhost", "127.0.0.1", "::1"]);

async function serve(args) {
    if (args.includes("--branch")) {
        console.error("visual-review serve: --branch is gone: a --results preview is look only and has no Finish");
        return 2;
    }
    const { values } = parseArgs({
        args,
        options: {
            "master-run": { type: "string" },
            results: { type: "string" },
        },
    });
    const { PORT, HOST = "localhost", HTTPS_CERT_PATH, HTTPS_KEY_PATH } = process.env;
    const masterRun = values["master-run"] === undefined ? undefined : Number(values["master-run"]);
    const https = Boolean(HTTPS_CERT_PATH && HTTPS_KEY_PATH);
    if (!PORT || (masterRun !== undefined && !Number.isInteger(masterRun))) {
        console.error(HELP.serve);
        return 2;
    }
    if (!https && !LOOPBACK.has(HOST)) {
        console.error(
            `visual-review serve: HOST=${HOST} is reachable from other machines, so the page needs HTTPS: ` +
                "set HTTPS_CERT_PATH and HTTPS_KEY_PATH, or serve on localhost",
        );
        return 2;
    }
    const { root, config } = await settings();
    const { readFileSync } = await import("node:fs");
    const { lfsProblem } = await import("./lib/accept.mjs");
    const { ghRunner } = await import("./lib/github.mjs");
    const { createApp, sessionToken } = await import("./lib/serve.mjs");
    const lfs = await lfsProblem(root);
    if (lfs) {
        console.error(`visual-review serve: ${lfs}`);
        return 1;
    }
    const tmp = join(root, config.workDir);
    const token = sessionToken(join(tmp, "state"));
    const origin = `${https ? "https" : "http"}://${HOST.includes(":") ? `[${HOST}]` : HOST}:${PORT}`;
    // Offline: a local results directory is a preview, so nothing is posted to GitHub.
    const offline = async (ghArgs, input) => {
        console.log(`gh (offline, not run): ${ghArgs.join(" ")}\n${input ?? ""}`);
        return JSON.stringify({ html_url: null });
    };
    const certs = https ? `HTTPS_CERT_PATH=${HTTPS_CERT_PATH} HTTPS_KEY_PATH=${HTTPS_KEY_PATH} ` : "";
    const app = createApp({
        repo: root,
        gh: values.results ? offline : ghRunner(root),
        config,
        tmp,
        token,
        origin,
        masterRun,
        results: values.results && resolve(values.results),
        // What the owner types to run this server from their own shell, so Finish signs with
        // their key rather than the environment of whoever started it (an agent, say).
        startCommand:
            `cd ${root} && PORT=${PORT} HOST=${HOST} ${certs}node ${process.argv[1]} serve ${args.join(" ")}`.trim(),
    });
    const server = https
        ? (await import("node:https")).createServer(
              { cert: readFileSync(HTTPS_CERT_PATH), key: readFileSync(HTTPS_KEY_PATH) },
              app,
          )
        : (await import("node:http")).createServer(app);
    await new Promise((done) => server.listen({ port: Number(PORT), host: HOST }, () => done(null)));
    console.log(`visual-review: open ${origin}/#token=${token}`);
    // Keep running until the process is stopped.
    await new Promise(() => {});
    return 0;
}

async function compare(args) {
    const { values } = parseArgs({
        args,
        options: {
            baselines: { type: "string" },
            captures: { type: "string" },
            threshold: { type: "string" },
            "include-aa": { type: "boolean", default: false },
        },
    });
    const { classify, DEFAULT_THRESHOLD, readBaseline } = await import("./lib/compare.mjs");
    const threshold = Number(values.threshold ?? DEFAULT_THRESHOLD);
    if (!values.baselines || !values.captures || !(threshold >= 0 && threshold <= 1)) {
        console.error(HELP.compare);
        return 2;
    }
    const pngs = async (dir) => (await readdir(dir)).filter((f) => f.endsWith(".png"));
    const read = (dir, file, present) =>
        present.includes(file) ? (dir === values.baselines ? readBaseline : readFile)(join(dir, file)) : null;
    const [baselines, captures] = await Promise.all([pngs(values.baselines), pngs(values.captures)]);
    const counts = {};
    for (const file of [...new Set([...baselines, ...captures])].sort()) {
        const item = classify({
            baseline: await read(values.baselines, file, baselines),
            first: await read(values.captures, file, captures),
            threshold,
            includeAA: values["include-aa"],
        });
        counts[item.status] = (counts[item.status] ?? 0) + 1;
        if (item.status !== "unchanged") {
            console.log(JSON.stringify({ file, ...item }));
        }
    }
    console.log(JSON.stringify({ summary: counts }));
    return Object.keys(counts).some((status) => status !== "unchanged") ? 1 : 0;
}

async function gate(args) {
    const { runGate } = await import("./gate.mjs");
    return runGate(args);
}

async function init(args) {
    const { values } = parseArgs({ args, options: { force: { type: "boolean", default: false } } });
    const { repoRoot } = await import("./lib/config.mjs");
    const { init: run } = await import("./lib/init.mjs");
    const root = repoRoot();
    for (const line of run(root, { force: values.force })) {
        console.log(line);
    }
    return 0;
}

async function installBrowser() {
    const { createRequire } = await import("node:module");
    const { spawnSync } = await import("node:child_process");
    const { dirname } = await import("node:path");
    let pkg;
    try {
        pkg = createRequire(import.meta.url).resolve("playwright/package.json");
    } catch {
        console.error(
            "visual-review: playwright is not installed; add it to your devDependencies (npm i -D playwright)",
        );
        return 1;
    }
    const cli = join(dirname(pkg), JSON.parse(await readFile(pkg, "utf8")).bin.playwright);
    return spawnSync(process.execPath, [cli, "install", "--with-deps", "chromium"], { stdio: "inherit" }).status ?? 1;
}

const [name, ...rest] = process.argv.slice(2);
if (name === undefined || name === "--help" || name === "-h" || name === "help") {
    console.log(MAIN_HELP);
    process.exit(name === undefined ? 2 : 0);
}
if (name === "--version" || name === "-v") {
    console.log(JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8")).version);
    process.exit(0);
}
const run = Object.hasOwn(COMMANDS, name) ? COMMANDS[name] : undefined;
if (run === undefined) {
    console.error(`visual-review: unknown command "${name}"\n\n${MAIN_HELP}`);
    process.exit(2);
}
if (rest.includes("--help") || rest.includes("-h")) {
    const text = HELP[name] ?? (await import("./gate.mjs")).GATE_USAGE;
    console.log(text);
    process.exit(0);
}
try {
    process.exitCode = await run(rest);
} catch (err) {
    // A bad option, a missing config or a failed git call: say what, without a stack.
    if (err?.code?.startsWith?.("ERR_PARSE_ARGS") || /visual-review\.config\.json|git repository/.test(err?.message)) {
        console.error(`visual-review ${name}: ${err.message}`);
        process.exitCode = 2;
    } else {
        throw err;
    }
}

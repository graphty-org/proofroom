#!/usr/bin/env node
/**
 * visual-review: capture Storybook stories, compare them with the baselines in git, and serve
 * the page where the owner accepts or rejects the differences.
 *
 * Every command runs in a git checkout and reads its settings from visual-review.config.json at
 * the checkout's root (see config.mjs and the README). `visual-review <command> --help` describes
 * each command. Each command's modules are imported only when it runs, so `gate` needs nothing
 * beyond Node's standard library and runs from a checkout without an install.
 */

import { readFile, readdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { parseArgs } from "node:util";


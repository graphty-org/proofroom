/**
 * The repository and its config, loaded only by the commands that need them.
 * @returns {Promise<{ root: string, config: object }>} the checkout's root and its settings
 */
async function settings() {
    const { loadConfig, repoRoot } = await import("./lib/config.mjs");
    const root = repoRoot();
    return { root, config: loadConfig(root) };
}

/** @type {Record<string, { type: "string" }>} */
const SHOOT_OPTIONS = {
    project: { type: "string" },
    out: { type: "string" },
    storybook: { type: "string" },
    baselines: { type: "string" },
    workers: { type: "string" },
    stories: { type: "string" },
};

/**
 * What `capture` and `run` shoot, from their options and the config.
 * @param {Record<string, any>} values the parsed options
 * @param {string} help the command's usage, printed when an option is missing
 * @returns {Promise<object | null>} capture()'s options, or null after printing the usage
 */
async function shootOptions(values, help) {
    const { root, config } = await settings();
    const project = Object.hasOwn(config.projects, values.project ?? "") ? config.projects[values.project] : undefined;
    const workers = Number(values.workers ?? project?.workers);
    if (!project || !values.out || !(Number.isInteger(workers) && workers > 0)) {
        console.error(`${help}\n\nprojects: ${Object.keys(config.projects).join(", ")}`);
        return null;
    }
    return {
        project: values.project,
        storybook: resolve(values.storybook ?? join(root, project.storybook)),
        baselines: resolve(values.baselines ?? join(root, config.baselines, values.project)),
        out: resolve(values.out),
        workers,
        waitFor: project.waitFor,
        stories: values.stories ? values.stories.split(",").filter(Boolean) : null,
        fontconfig: config.fontconfig ? join(root, config.fontconfig) : null,
    };
}

/**
 * Runs a command's work, turning a failure of the tool into exit code 2 with its message.
 * @param {string} name the command
 * @param {() => Promise<number>} work the work, resolving to the exit code
 * @returns {Promise<number>} the exit code
 */
async function toolExit(name, work) {
    try {
        return await work();
    } catch (err) {
        console.error(`proofroom ${name}: ${err?.message ?? err}`);
        return 2;
    }
}

const printLine = (line) => console.log(JSON.stringify(line, (key, value) => (key === "bytes" ? undefined : value)));

async function capture(args) {
    const { values } = parseArgs({ args, options: { ...SHOOT_OPTIONS, ndjson: { type: "boolean", default: false } } });
    const options = await shootOptions(values, HELP.capture);
    if (!options) {
        return 2;
    }
    // Playwright is capture's only dependency, so it loads only for the commands that shoot.
    const { capture: shoot } = await import("../capture/capture.mjs");
    return toolExit("capture", async () => {
        for await (const line of shoot(options)) {
            if (values.ndjson) {
                printLine(line);
            }
        }
        return 0;
    });
}

async function run(args) {
    const { values } = parseArgs({
        args,
        options: {
            ...SHOOT_OPTIONS,
            reference: { type: "string" },
            retries: { type: "string" },
            junit: { type: "string" },
            "no-fail": { type: "boolean", default: false },
        },
    });
    const retries = Number(values.retries ?? 0);
    const options = await shootOptions(values, HELP.run);
    if (!options || !(Number.isInteger(retries) && retries >= 0 && retries <= MAX_ATTEMPTS)) {
        if (options) {
            console.error(HELP.run);
        }
        return 2;
    }
    const { run: shootAndCompare } = await import("../capture/capture.mjs");
    return toolExit("run", async () => {
        const { passed } = await shootAndCompare({
            ...options,
            reference: values.reference ? resolve(values.reference) : null,
            retries,
            junit: resolve(values.junit ?? join(options.out, "junit.xml")),
            print: printLine,
        });
        return passed || values["no-fail"] ? 0 : 1;
    });
}

async function reference(args) {
    const { values } = parseArgs({ args, options: { project: { type: "string" }, out: { type: "string" } } });
    if (!values.project || !values.out) {
        console.error(HELP.reference);
        return 2;
    }
    const { root, config } = await settings();
    const { ghRunner } = await import("./lib/github.mjs");
    const { captureStoreFor } = await import("./lib/adapters/index.mjs");
    const store = captureStoreFor(config, { gh: ghRunner(root) });
    console.log((await store.newestDefault(values.project, resolve(values.out), config)) ?? "");
    return 0;
}

const LOOPBACK = new Set(["localhost", "127.0.0.1", "::1"]);

/**
 * The address the review page is served at.
 * @param {boolean} https whether it is served over HTTPS
 * @param {string} host the host it binds (an IPv6 address is bracketed)
 * @param {string} port the port
 * @returns {string} the origin
 */
function serveOrigin(https, host, port) {
    const scheme = https ? "https" : "http";
    const name = host.includes(":") ? `[${host}]` : host;
    return `${scheme}://${name}:${port}`;
}

/**
 * The server for the review page.
 * @param {import("node:http").RequestListener} app the request handler
 * @param {{ cert: string, key: string } | false} tls the certificate and key files for HTTPS, or
 *     false for HTTP
 * @returns {Promise<import("node:http").Server>} the server, not yet listening
 */
async function createServer(app, tls) {
    if (!tls) {
        return (await import("node:http")).createServer(app);
    }
    const { createServer: createHttps } = await import("node:https");
    const { readFileSync } = await import("node:fs");
    return createHttps({ cert: readFileSync(tls.cert), key: readFileSync(tls.key) }, app);
}

/**
 * serve's run option: `--candidate next` (the candidate mode), or a run id from `--candidate <id>` or
 * its old name `--master-run <id>`.
 * @param {{ candidate?: string, "master-run"?: string }} values the parsed options
 * @returns {{ next: boolean, masterRun: number | undefined }} the mode and the run id, NaN when not one
 */
function runOption(values) {
    const next = values.candidate === "next";
    const run = next ? values["master-run"] : (values.candidate ?? values["master-run"]);
    return { next, masterRun: run === undefined ? undefined : Number(run) };
}

async function serve(args) {
    if (args.includes("--branch")) {
        console.error("proofroom serve: --branch is gone: a --results preview is look only and has no Finish");
        return 2;
    }
    const { values } = parseArgs({
        args,
        options: {
            "master-run": { type: "string" },
            candidate: { type: "string" },
            results: { type: "string" },
            previews: { type: "string" },
            ui: { type: "string" },
        },
    });
    const { PORT, HOST = "localhost", HTTPS_CERT_PATH, HTTPS_KEY_PATH } = process.env;
    const { next, masterRun } = runOption(values);
    const https = Boolean(HTTPS_CERT_PATH && HTTPS_KEY_PATH);
    const ui = values.ui ?? "review";
    if (!PORT || (masterRun !== undefined && !Number.isInteger(masterRun)) || !["review", "next"].includes(ui)) {
        console.error(HELP.serve);
        return 2;
    }
    if (!https && !LOOPBACK.has(HOST)) {
        console.error(
            `proofroom serve: HOST=${HOST} is reachable from other machines, so the page needs HTTPS: ` +
                "set HTTPS_CERT_PATH and HTTPS_KEY_PATH, or serve on localhost",
        );
        return 2;
    }
    const { root, config } = await settings();
    if (next && !config.candidates) {
        console.error("proofroom serve: --candidate next needs the config's `candidates` command");
        return 2;
    }
    const { lfsProblem } = await import("./lib/accept.mjs");
    const { exec, ghRunner } = await import("./lib/github.mjs");
    const { createApp, sessionToken } = await import("./lib/serve.mjs");
    const lfs = await lfsProblem(root);
    if (lfs) {
        console.error(`proofroom serve: ${lfs}`);
        return 1;
    }
    const tmp = join(root, config.workDir);
    // The main checkout, not this worktree: a preview script run from any worktree writes there.
    const { execFileSync } = await import("node:child_process");
    const { dirname } = await import("node:path");
    const common = execFileSync("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], { cwd: root })
        .toString("utf8")
        .trim();
    const previews = values.previews ? resolve(values.previews) : join(dirname(common), config.workDir, "local");
    const token = sessionToken(join(tmp, "state"));
    const origin = serveOrigin(https, HOST, PORT);
    // Offline: a local results directory is a preview, so nothing is posted to GitHub.
    const offline = async (ghArgs, input) => {
        console.log(`gh (offline, not run): ${ghArgs.join(" ")}\n${input ?? ""}`);
        return JSON.stringify({ html_url: null });
    };
    const certs = https ? `HTTPS_CERT_PATH=${HTTPS_CERT_PATH} HTTPS_KEY_PATH=${HTTPS_KEY_PATH} ` : "";
    const app = createApp({
        repo: root,
        gh: values.results ? offline : ghRunner(root),
        config,
        tmp,
        token,
        origin,
        masterRun,
        candidates: next ? async () => JSON.parse(await exec("sh", ["-c", config.candidates], { cwd: root })) : null,
        results: values.results && resolve(values.results),
        warm: true,
        previews: values.results ? null : previews,
        ui: /** @type {"review" | "next"} */ (ui),
        // What the owner types to run this server from their own shell, so Finish signs with
        // their key rather than the environment of whoever started it (an agent, say).
        startCommand:
            `cd ${root} && PORT=${PORT} HOST=${HOST} ${certs}node ${process.argv[1]} serve ${args.join(" ")}`.trim(),
    });
    const server = await createServer(app, https && { cert: HTTPS_CERT_PATH, key: HTTPS_KEY_PATH });
    await new Promise((done) => server.listen({ port: Number(PORT), host: HOST }, () => done(null)));
    console.log(`proofroom: open ${origin}/#token=${token}`);
    console.log(`proofroom: server ${app.serverId}: the page's session cookie is vr_session_${app.serverId}`);
    // Keep running until the process is stopped.
    await new Promise(() => {});
    return 0;
}

async function notify(args) {
    const { values } = parseArgs({ args, options: { command: { type: "string" }, gap: { type: "string" } } });
    const text = values.command ?? process.env.VISUAL_REVIEW_NOTIFY;
    let command;
    try {
        command = JSON.parse(text ?? "null");
    } catch {
        command = null;
    }
    const gap = Number(values.gap ?? 10);
    if (
        !Array.isArray(command) ||
        command.length === 0 ||
        !command.every((a) => typeof a === "string") ||
        Number.isNaN(gap) ||
        gap < 0
    ) {
        console.error(HELP.notify);
        return 2;
    }
    const { root, config } = await settings();
    const { notifyOnce } = await import("./lib/inbox.mjs");
    const stateDir = join(root, config.workDir, "state");
    console.log(`proofroom notify: watching ${join(stateDir, "inbox.json")}`);
    const tick = async () => {
        try {
            const sent = await notifyOnce({ stateDir, command, gap: gap * 60000 });
            if (sent.length > 0) {
                console.log(`proofroom notify: announced ${sent.map((r) => "#" + r.pr).join(", ")}`);
            }
        } catch (err) {
            console.error(`proofroom notify: ${err.message}`);
        }
        setTimeout(tick, 30000);
    };
    await tick();
    // Keep running until the process is stopped.
    await new Promise(() => {});
    return 0;
}

